//! A wall washer's measured light, for a spot light's profile
//! (`sgl_3d::LightProfile`, `sgl_3d::SpotProfile`): an LM-63 file written in
//! code, so the examples carry no photometric file and native and browser
//! builds share it. A game loads its fixtures' `.ies` files the same way,
//! as text, with `LightProfile::from_ies`.

/// An LM-63-2002 file of type C photometry, measured every 5° from the
/// nadir to 90° and every 22.5° round the luminaire: a downlight that
/// throws its light toward its 0° side, as a wall washer throws it onto the
/// wall in front of it. Straight down it shines 600 cd; toward its 0°
/// side it rises to 1000 cd at 40°, behind it, toward 180°, it falls to
/// nothing there, and every side fades to nothing at 80°.
pub fn wall_washer_ies() -> String {
    let vertical: Vec<f64> = (0..=18).map(|step| f64::from(step) * 5.).collect();
    let horizontal: Vec<f64> = (0..=16).map(|step| f64::from(step) * 22.5).collect();
    let list = |values: &[f64]| {
        values
            .iter()
            .map(|value| format!("{value:.1}"))
            .collect::<Vec<_>>()
            .join(" ")
    };
    let mut text = format!(
        "IESNA:LM-63-2002\n[TEST] Generated by the SGL examples\n[LUMINAIRE] Wall washer\nTILT=NONE\n1 -1 1 {} {} 1 2 0.1 0.1 0.05\n1 1 20\n{}\n{}\n",
        vertical.len(),
        horizontal.len(),
        list(&vertical),
        list(&horizontal),
    );
    for azimuth in &horizontal {
        // 1 toward the 0° side, 0 behind it.
        let forward = 0.5 * (1. + azimuth.to_radians().cos());
        let plane: Vec<f64> = vertical
            .iter()
            .map(|polar| {
                // From the nadir's 600 cd to the throw's at 40°, then
                // fading to nothing at 80°.
                let toward = (polar / 40.).min(1.);
                let fade = (1. - (polar - 40.).max(0.) / 40.).max(0.);
                (600. * (1. - toward) + 1000. * forward * toward) * fade
            })
            .collect();
        text.push_str(&list(&plane));
        text.push('\n');
    }
    text
}
