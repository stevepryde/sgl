//! Material images: decoded RGBA8 texels, or a block-compressed mip chain as
//! a game's export step stores it, read from KTX2 as Bevy 9d12036 reads it
//! (`crates/bevy_image/src/ktx2.rs`, `ktx2_buffer_to_image`: its stored
//! levels, Zstandard supercompression, and block formats sampled as sRGB
//! or linear by the channel that uses it). MIT OR Apache-2.0
//! (src/LICENSE-bevy.txt).
use std::borrow::Cow;

use super::asset::Result;
use super::load_budget::{Budget, DEFAULT_LOAD_BYTES, LoadBudget, MAX_IMAGE_SIDE};

/// An image materials sample. Its colour space belongs to each channel that
/// samples it: base and emissive maps read it as sRGB, the others as linear
/// data.
#[derive(Clone, Debug)]
pub enum Image {
    /// Decoded texels. The scene filters their mip chain when it adds them,
    /// in linear light for a channel that samples them as colour.
    Rgba8(image::RgbaImage),
    /// A block-compressed mip chain, uploaded as stored. Adding it needs
    /// the format’s matching BC, ETC2 or ASTC device feature.
    Compressed(CompressedImage),
    /// RGBA8 levels prepared on a caller-owned worker, uploaded without filtering.
    Rgba8Mips(Rgba8MipChain),
}

/// A block-compressed image's encoding.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CompressedFormat {
    /// BC7: 16 bytes per block of 4x4 RGBA texels.
    Bc7,
    /// ETC2 RGB with EAC alpha: 16 bytes per 4x4 block.
    Etc2Rgba8,
    /// ASTC LDR RGBA: 16 bytes per 4x4 block.
    Astc4x4,
}

/// A block-compressed mip chain. A scene adds it when its sides are
/// multiples of the block size and no larger than 16384, and it holds one
/// to a full chain of levels, each of the size its level needs; otherwise
/// it refuses it with
/// `SceneError::InvalidCompressedImage`.
#[derive(Clone, Debug)]
pub struct CompressedImage {
    pub format: CompressedFormat,
    /// Level 0's width in texels.
    pub width: u32,
    /// Level 0's height in texels.
    pub height: u32,
    /// The stored levels, level 0 first and each next one half the size
    /// (at least one texel): each one's blocks row by row, a level's edge
    /// blocks whole. Filter a colour image's levels in linear light.
    pub levels: Vec<Vec<u8>>,
    /// ETC2/ASTC level 0 decoded by the game's offline export tool, in the
    /// same encoded-channel RGBA8 space as the compressed raster texture.
    /// Optional for raster-only material images. Required for rays and decals,
    /// and must match width/height when present. SGL checks
    /// shape, not pixel equivalence. Costs four additional bytes per texel.
    /// BC7 must leave this `None`: its rays continue to decode the blocks.
    pub decoded_level_0: Option<image::RgbaImage>,
}

/// Invalid caller-authored image preparation input.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ImageError {
    /// A side is zero or greater than the content limit of 16384 texels.
    InvalidDimensions,
    /// Generated levels exceed the load budget, or the float filtering
    /// scratch image cannot fit one addressable allocation.
    BudgetExceeded,
}

impl std::fmt::Display for ImageError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::InvalidDimensions => "image sides must be between 1 and 16384 texels",
            Self::BudgetExceeded => "prepared mip chains exceed the load budget or addressable filtering allocation; split or resize the image",
        })
    }
}
impl std::error::Error for ImageError {}

/// Immutable RGBA8 mip chains prepared without a device or library thread.
/// The same image may serve colour and data channels: RGB is filtered in
/// linear light for colour and directly for data; alpha is always linear.
/// Retains both chains (approximately twice a full RGBA8 chain). Games can
/// prepare this `Send` value on their own worker before adding materials.
/// Retained generated bytes are bounded by the content load budget (4 GiB
/// native, 1 GiB wasm). Filtering scratch, the source and allocator capacity
/// are additional; this is not a peak-memory guarantee.
#[derive(Clone, Debug)]
pub struct Rgba8MipChain {
    color: Vec<image::RgbaImage>,
    data: Vec<image::RgbaImage>,
}

impl Rgba8MipChain {
    /// Builds complete colour and data chains, with level 0 unchanged.
    pub fn new(image: image::RgbaImage) -> std::result::Result<Self, ImageError> {
        check_mip_allocation(image.dimensions(), DEFAULT_LOAD_BYTES, isize::MAX as u64)?;
        Ok(Self {
            color: rgba8_levels(&image, true),
            data: rgba8_levels(&image, false),
        })
    }

    /// Level 0 first, followed by the stored half-size levels down to 1x1.
    /// `srgb` selects the linear-light colour chain rather than the data chain.
    pub fn levels(&self, srgb: bool) -> &[image::RgbaImage] {
        if srgb { &self.color } else { &self.data }
    }
}

/// Bound expansion before any generated level or float scratch is allocated.
fn check_mip_allocation(
    (width, height): (u32, u32),
    budget: u64,
    allocation_max: u64,
) -> std::result::Result<(), ImageError> {
    if width == 0 || height == 0 || width.max(height) > MAX_IMAGE_SIDE {
        return Err(ImageError::InvalidDimensions);
    }
    let mut retained = 0u64;
    let (mut w, mut h) = (width, height);
    loop {
        retained = retained
            .checked_add(u64::from(w) * u64::from(h) * 8)
            .ok_or(ImageError::BudgetExceeded)?;
        if w == 1 && h == 1 {
            break;
        }
        w = (w / 2).max(1);
        h = (h / 2).max(1);
    }
    let scratch = if width.max(height) > 1 {
        u64::from(width) * u64::from(height) * 16
    } else {
        0
    };
    if retained > budget || scratch > allocation_max {
        return Err(ImageError::BudgetExceeded);
    }
    Ok(())
}

/// CPU-only mip filtering, shared by preparation and the convenience upload.
pub(crate) fn rgba8_levels(image: &image::RgbaImage, srgb: bool) -> Vec<image::RgbaImage> {
    let mut levels = vec![image.clone()];
    while levels
        .last()
        .unwrap()
        .width()
        .max(levels.last().unwrap().height())
        > 1
    {
        let mip = levels.last().unwrap();
        let mut linear = image::Rgba32FImage::new(mip.width(), mip.height());
        for (to, from) in linear.pixels_mut().zip(mip.pixels()) {
            for c in 0..4 {
                let x = from[c] as f32 / 255.0;
                to[c] = if srgb && c < 3 {
                    super::srgb::to_linear(x)
                } else {
                    x
                };
            }
        }
        let small = image::imageops::resize(
            &linear,
            (mip.width() / 2).max(1),
            (mip.height() / 2).max(1),
            image::imageops::FilterType::Triangle,
        );
        let mut mip = image::RgbaImage::new(small.width(), small.height());
        for (to, from) in mip.pixels_mut().zip(small.pixels()) {
            for c in 0..4 {
                let x = if srgb && c < 3 {
                    super::srgb::from_linear(from[c])
                } else {
                    from[c]
                };
                to[c] = (x.clamp(0.0, 1.0) * 255.0).round() as u8;
            }
        }
        levels.push(mip);
    }
    levels
}

/// Texels on each side of a block.
const BLOCK: u32 = 4;
/// Bytes of a BC7 block.
const BLOCK_BYTES: usize = 16;

/// ktx2 0.5.0 eagerly parses the DFD, incrementing dimension bytes in u8.
/// Check its block bounds and unsupported 256-texel dimensions before that
/// parser. KTX 2.0 section 3.10 / Khronos Data Format 1.4 define this layout.
fn check_ktx2_dfd(bytes: &[u8]) -> Result<()> {
    let raw = bytes
        .get(..ktx2::Header::LENGTH)
        .ok_or("invalid KTX2 file: truncated header")?;
    let header = ktx2::Header::from_bytes(raw.try_into()?)
        .map_err(|error| format!("invalid KTX2 file: {error}"))?;
    let index = header.index;
    let end = index
        .dfd_byte_offset
        .checked_add(index.dfd_byte_length)
        .ok_or("invalid KTX2 data format descriptor: range overflow")?;
    let descriptor = bytes
        .get(index.dfd_byte_offset as usize..end as usize)
        .ok_or("invalid KTX2 data format descriptor: truncated section")?;
    let mut blocks = descriptor
        .get(4..)
        .ok_or("invalid KTX2 data format descriptor: truncated size")?;
    while !blocks.is_empty() {
        let header = blocks
            .get(..ktx2::dfd::BlockHeader::LENGTH)
            .ok_or("invalid KTX2 data format descriptor: truncated block header")?;
        let size = u16::from_le_bytes(header[6..8].try_into()?) as usize;
        if size < ktx2::dfd::BlockHeader::LENGTH {
            return Err(
                "invalid KTX2 data format descriptor: block shorter than its header".into(),
            );
        }
        let block = blocks
            .get(..size)
            .ok_or("invalid KTX2 data format descriptor: truncated block")?;
        // Match the same vendor/type/version as ktx2's basic-block parser;
        // other descriptor blocks have different layouts.
        if header[..6] == ktx2::dfd::BlockHeader::BASIC.as_bytes(0)[..6] {
            let dimensions = block
                .get(12..16)
                .ok_or("invalid KTX2 data format descriptor: truncated dimensions")?;
            if dimensions.contains(&0xff) {
                return Err(
                    "invalid KTX2 data format descriptor: unsupported texel-block dimension".into(),
                );
            }
        }
        blocks = &blocks[size..];
    }
    Ok(())
}

impl Image {
    /// Retained caller-supplied bytes count in the same decoded budget as
    /// imported geometry and decoded images, including both prepared mip
    /// chains and compressed images' offline-decoded companions.
    pub(super) fn charge_bytes(&self, budget: &mut Budget) -> Result<()> {
        match self {
            Self::Rgba8(image) => budget.charge(image.as_raw().len() as u64),
            Self::Rgba8Mips(image) => {
                for level in image.color.iter().chain(&image.data) {
                    budget.charge(level.as_raw().len() as u64)?;
                }
                Ok(())
            }
            Self::Compressed(image) => {
                for level in &image.levels {
                    budget.charge(level.len() as u64)?;
                }
                if let Some(decoded) = &image.decoded_level_0 {
                    budget.charge(decoded.as_raw().len() as u64)?;
                }
                Ok(())
            }
        }
    }

    /// Level 0's width and height in texels.
    pub(crate) fn size(&self) -> [u32; 2] {
        match self {
            Self::Rgba8(image) => [image.width(), image.height()],
            Self::Rgba8Mips(image) => [
                image.levels(false)[0].width(),
                image.levels(false)[0].height(),
            ],
            Self::Compressed(image) => [image.width, image.height],
        }
    }

    /// Level 0's texels for the decal atlas. BC7 decodes its own blocks;
    /// ETC2/ASTC return none without their offline decoded companion.
    pub(crate) fn texels(&self) -> Option<Cow<'_, image::RgbaImage>> {
        Some(match self {
            Self::Rgba8(image) => Cow::Borrowed(image),
            Self::Rgba8Mips(image) => Cow::Borrowed(&image.levels(false)[0]),
            Self::Compressed(image) => match &image.decoded_level_0 {
                Some(texels) => Cow::Borrowed(texels),
                None if image.format == CompressedFormat::Bc7 => Cow::Owned(image.decode_level_0()),
                None => return None,
            },
        })
    }
}

impl CompressedImage {
    /// The image a KTX2 file holds: one 2D image of BC7, ETC2 RGBA8 or
    /// ASTC 4x4 blocks (the channel
    /// that samples it picks sRGB or linear, as Bevy's loader does), with
    /// its stored levels, uncompressed or supercompressed with Zstandard.
    /// ETC2/ASTC used by material rays or decals need an offline companion
    /// supplied through `from_ktx2_with_decoded_level_0` instead.
    /// Refuses malformed data format descriptors, sides above 16384,
    /// invalid block dimensions or mip counts,
    /// and levels whose declared or decoded size differs from their block
    /// size. The total decoded chain is budgeted before level allocation;
    /// the decoder bounds regenerated blocks before buffer growth.
    pub fn from_ktx2(bytes: &[u8]) -> Result<Self> {
        Self::from_ktx2_with_budget(bytes, LoadBudget::default())
    }

    /// Read a supported block format with explicit source and decoded safety caps. The entire
    /// KTX2 source slice is checked before parsing, and the decoded chain
    /// before allocating levels. Caps do not raise dimension/device limits
    /// or guarantee sufficient memory. Use the same budget in the enclosing
    /// glTF's `LoadOptions` when supplying this image to an import.
    pub fn from_ktx2_with_budget(bytes: &[u8], budget: LoadBudget) -> Result<Self> {
        Budget::source(budget).charge(bytes.len() as u64)?;
        Self::read_ktx2(bytes, &mut Budget::decoded(budget))
    }

    /// Reads ETC2 RGBA8 or ASTC LDR 4x4 with the game's offline-decoded
    /// level 0 for ray materials and decals. The companion must decode these
    /// exact compressed blocks, with unchanged encoded-channel RGBA8 bytes.
    /// Shape and combined decoded-byte budget are checked; pixel equivalence
    /// is the exporter's responsibility. Refuses a companion for BC7.
    pub fn from_ktx2_with_decoded_level_0(bytes: &[u8], decoded: image::RgbaImage) -> Result<Self> {
        Self::from_ktx2_with_decoded_level_0_and_budget(bytes, decoded, LoadBudget::default())
    }

    /// Read ETC2/ASTC with explicit source and decoded safety caps. The
    /// decoded cap includes both stored block levels and the RGBA8 companion.
    /// As with `from_ktx2_with_budget`, allocation working memory is additional.
    pub fn from_ktx2_with_decoded_level_0_and_budget(
        bytes: &[u8],
        decoded: image::RgbaImage,
        budget: LoadBudget,
    ) -> Result<Self> {
        Budget::source(budget).charge(bytes.len() as u64)?;
        Self::read_ktx2_with_decoded(bytes, Some(decoded), &mut Budget::decoded(budget))
    }

    fn read_ktx2(bytes: &[u8], budget: &mut Budget) -> Result<Self> {
        Self::read_ktx2_with_decoded(bytes, None, budget)
    }

    fn read_ktx2_with_decoded(
        bytes: &[u8],
        decoded_level_0: Option<image::RgbaImage>,
        budget: &mut Budget,
    ) -> Result<Self> {
        check_ktx2_dfd(bytes)?;
        let reader =
            ktx2::Reader::new(bytes).map_err(|error| format!("invalid KTX2 file: {error}"))?;
        let header = reader.header();
        let format = match header.format {
            Some(ktx2::Format::BC7_UNORM_BLOCK | ktx2::Format::BC7_SRGB_BLOCK) => {
                CompressedFormat::Bc7
            }
            Some(
                ktx2::Format::ETC2_R8G8B8A8_UNORM_BLOCK | ktx2::Format::ETC2_R8G8B8A8_SRGB_BLOCK,
            ) => CompressedFormat::Etc2Rgba8,
            Some(ktx2::Format::ASTC_4x4_UNORM_BLOCK | ktx2::Format::ASTC_4x4_SRGB_BLOCK) => {
                CompressedFormat::Astc4x4
            }
            other => {
                return Err(format!(
                    "KTX2 format {other:?} is not supported; store BC7, ETC2 RGBA8 or ASTC LDR 4x4"
                )
                .into());
            }
        };
        if header.pixel_depth > 1 || header.layer_count > 1 || header.face_count != 1 {
            return Err("a KTX2 material image must be one 2D image".into());
        }
        if header.level_count == 0 {
            return Err("the KTX2 file asks for generated mips; store its mip chain".into());
        }
        let mut image = Self {
            format,
            width: header.pixel_width,
            height: header.pixel_height.max(1),
            levels: Vec::new(),
            decoded_level_0,
        };
        let full = 32 - image.width.max(image.height).leading_zeros();
        if image.width == 0
            || image.width > MAX_IMAGE_SIDE
            || image.height > MAX_IMAGE_SIDE
            || !image.width.is_multiple_of(BLOCK)
            || !image.height.is_multiple_of(BLOCK)
            || header.level_count > full
        {
            return Err(format!("invalid KTX2 dimensions or mip count; store block-aligned sides no larger than {MAX_IMAGE_SIDE} and at most a full mip chain").into());
        }
        if !image.companion_is_valid() {
            return Err("BC7 must have no decoded companion; any ETC2/ASTC decoded level 0 must match the compressed dimensions".into());
        }
        if let Some(decoded) = &image.decoded_level_0 {
            budget.charge(decoded.as_raw().len() as u64)?;
        }
        // Validate every declared level and the whole chain before allocating
        // any decoded level. Header bounds above also make level_bytes safe.
        for (index, level) in reader.levels().enumerate() {
            let expected = image.level_bytes(index);
            if level.uncompressed_byte_length != expected as u64 {
                return Err(format!(
                    "KTX2 level {index} declares {} decoded bytes; expected {expected}",
                    level.uncompressed_byte_length
                )
                .into());
            }
            budget.charge(expected as u64)?;
        }
        image.levels = reader
            .levels()
            .enumerate()
            .map(|(index, level)| {
                let expected = image.level_bytes(index);
                let decoded = match header.supercompression_scheme {
                    None => {
                        if level.data.len() != expected {
                            return Err(format!(
                                "KTX2 level {index} has {} bytes; expected {expected}",
                                level.data.len()
                            )
                            .into());
                        }
                        level.data.to_vec()
                    }
                    Some(ktx2::SupercompressionScheme::Zstandard) => {
                        // Unlike a streaming history buffer, this one-shot
                        // decoder bounds growth before literals/sequences are
                        // written and never allocates the advertised window.
                        let mut decoded = Vec::new();
                        crate::content::zstandard::decompress(
                            level.data,
                            expected + 1,
                            &mut decoded,
                        )
                        .map_err(|error| format!("KTX2 level {index}: {error}"))?;
                        decoded
                    }
                    Some(other) => return Err(format!(
                        "KTX2 supercompression {other:?} is not supported; use Zstandard or none"
                    )
                    .into()),
                };
                if decoded.len() != expected {
                    return Err(format!(
                        "KTX2 level {index} decoded to {} bytes; expected {expected}",
                        decoded.len()
                    )
                    .into());
                }
                Ok(decoded)
            })
            .collect::<Result<Vec<_>>>()?;
        Ok(image)
    }

    /// The bytes level `level` holds: its blocks, a partial edge block whole.
    pub(crate) fn level_bytes(&self, level: usize) -> usize {
        let side = |size: u32| (size >> level).max(1).div_ceil(BLOCK) as usize;
        side(self.width) * side(self.height) * BLOCK_BYTES
    }

    /// Whether the scene can upload it: sides that are multiples of the
    /// block size (wgpu's rule for a block-compressed level 0) no larger
    /// than KTX2 loading allows, which also keeps `level_bytes` within a
    /// 32-bit `usize`, and one to a full chain of levels, each of its size.
    pub(crate) fn is_valid(&self) -> bool {
        let full = (32 - self.width.max(self.height).leading_zeros()) as usize;
        self.width > 0
            && self.height > 0
            && self.companion_is_valid()
            && self.width.is_multiple_of(BLOCK)
            && self.height.is_multiple_of(BLOCK)
            && self.width <= MAX_IMAGE_SIDE
            && self.height <= MAX_IMAGE_SIDE
            && (1..=full).contains(&self.levels.len())
            && self
                .levels
                .iter()
                .enumerate()
                .all(|(level, bytes)| bytes.len() == self.level_bytes(level))
    }

    /// Companion shape is part of the image invariant, even for caller-built data.
    fn companion_is_valid(&self) -> bool {
        match (self.format, &self.decoded_level_0) {
            (_, None) => true,
            (CompressedFormat::Etc2Rgba8 | CompressedFormat::Astc4x4, Some(decoded)) => {
                decoded.dimensions() == (self.width, self.height)
            }
            _ => false,
        }
    }

    /// BC7 level 0 decoded with bcdec (MIT) as the GPU decodes it.
    /// A valid image only.
    fn decode_level_0(&self) -> image::RgbaImage {
        let mut texels = image::RgbaImage::new(self.width, self.height);
        let pitch = self.width as usize * 4;
        let blocks_wide = (self.width / BLOCK) as usize;
        let rows = texels.chunks_exact_mut(pitch * BLOCK as usize);
        for (blocks, row) in self.levels[0]
            .chunks_exact(blocks_wide * BLOCK_BYTES)
            .zip(rows)
        {
            for (column, block) in blocks.chunks_exact(BLOCK_BYTES).enumerate() {
                let at = column * BLOCK as usize * 4;
                match self.format {
                    CompressedFormat::Bc7 => bcdec_rs::bc7(block, &mut row[at..], pitch),
                    _ => unreachable!("browser formats require a predecoded companion"),
                }
            }
        }
        texels
    }
}

