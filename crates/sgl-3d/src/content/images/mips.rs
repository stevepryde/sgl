//! RGBA8 mip chains on the CPU (`Rgba8MipChain`): the same filter the mip
//! chain stage runs on the GPU (`stages::mip_chains`, the architecture's
//! Material mip chains), for a chain a game prepares itself and for a tool
//! that compresses levels, with the brute-force area model both filters'
//! tests hold them to.
use crate::content::load_budget::{DEFAULT_LOAD_BYTES, MAX_IMAGE_SIDE};

/// Invalid caller-authored image preparation input.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ImageError {
    /// A side is zero or greater than the content limit of 16384 texels.
    InvalidDimensions,
    /// Generated levels exceed the load budget.
    BudgetExceeded,
}

impl std::fmt::Display for ImageError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::InvalidDimensions => "image sides must be between 1 and 16384 texels",
            Self::BudgetExceeded => {
                "prepared mip chains exceed the load budget; split or resize the image"
            }
        })
    }
}
impl std::error::Error for ImageError {}

/// Immutable RGBA8 mip chains prepared without a device or library thread,
/// for a tool that compresses levels or a game that hands the scene chains
/// of its own: a scene builds a decoded image's chain on the GPU by the
/// same rule, so preparing one saves no frame time. Each level's texel is
/// the mean of the texels of the level above that it covers, weighted by
/// the area it covers of each (the architecture's Material mip chains).
/// The same image may serve colour and data channels: RGB is averaged in
/// linear light for colour and as stored for data; alpha is always
/// averaged as stored. Retains both chains (approximately twice a full
/// RGBA8 chain). This `Send` value can be prepared on any thread.
/// Retained generated bytes are bounded by the content load budget (4 GiB
/// native, 1 GiB wasm). The source and allocator capacity are additional;
/// this is not a peak-memory guarantee.
#[derive(Clone, Debug)]
pub struct Rgba8MipChain {
    color: Vec<image::RgbaImage>,
    data: Vec<image::RgbaImage>,
}

impl Rgba8MipChain {
    /// Builds complete colour and data chains, with level 0 unchanged.
    pub fn new(image: image::RgbaImage) -> std::result::Result<Self, ImageError> {
        check_mip_allocation(image.dimensions(), DEFAULT_LOAD_BYTES)?;
        Ok(Self {
            color: rgba8_levels(&image, true),
            data: rgba8_levels(&image, false),
        })
    }

    /// Level 0 first, followed by the stored half-size levels down to 1x1.
    /// `srgb` selects the linear-light colour chain rather than the data chain.
    pub fn levels(&self, srgb: bool) -> &[image::RgbaImage] {
        if srgb { &self.color } else { &self.data }
    }
}

/// Bound expansion before any generated level is allocated.
fn check_mip_allocation(
    (width, height): (u32, u32),
    budget: u64,
) -> std::result::Result<(), ImageError> {
    if width == 0 || height == 0 || width.max(height) > MAX_IMAGE_SIDE {
        return Err(ImageError::InvalidDimensions);
    }
    let mut retained = 0u64;
    let (mut w, mut h) = (width, height);
    loop {
        retained = retained
            .checked_add(u64::from(w) * u64::from(h) * 8)
            .ok_or(ImageError::BudgetExceeded)?;
        if w == 1 && h == 1 {
            break;
        }
        w = (w / 2).max(1);
        h = (h / 2).max(1);
    }
    if retained > budget {
        return Err(ImageError::BudgetExceeded);
    }
    Ok(())
}

/// The texels of a level `above` texels long that texel `at` of the level
/// below it covers along one axis, each with the share of the footprint it
/// holds as a numerator over `above` (the architecture's Material mip
/// chains): the one texel of a level one texel long; two texels equally
/// where the level above is even; and where it is odd, 2m + 1, three,
/// weighted m - at, m and at + 1. `stages/mip_chains.wgsl` is the same rule
/// for the GPU.
fn footprint(at: u32, above: u32) -> ([(u32, u32); 3], usize) {
    let below = above / 2;
    if above == 1 {
        ([(0, 1), (0, 0), (0, 0)], 1)
    } else if above.is_multiple_of(2) {
        ([(2 * at, below), (2 * at + 1, below), (0, 0)], 2)
    } else {
        (
            [
                (2 * at, below - at),
                (2 * at + 1, below),
                (2 * at + 2, at + 1),
            ],
            3,
        )
    }
}

/// sRGB's transfer function as tables for 8-bit texels, so filtering takes
/// no `powf` a texel: each code's linear value, and encoding by the linear
/// value at which each code begins.
struct Transfer {
    /// The linear value of each sRGB code.
    linear: [f32; 256],
    /// `starts[code]`: the least linear value that rounds to `code` or
    /// above. `starts[0]` is 0.
    starts: [f32; 256],
    /// The code a linear value at the start of each of `Self::BUCKETS`
    /// equal steps of 0..=1 encodes to, from which `encode` steps up past
    /// the `starts` within the step: a few at most, since past the first
    /// two they lie no closer than about 1 / (255 * 12.92), the curve's
    /// linear toe.
    coarse: [u8; Self::BUCKETS + 1],
}

impl Transfer {
    const BUCKETS: usize = 4096;

    fn get() -> &'static Self {
        static TABLES: std::sync::OnceLock<Transfer> = std::sync::OnceLock::new();
        TABLES.get_or_init(|| {
            let linear =
                std::array::from_fn(|code| crate::content::srgb::to_linear(code as f32 / 255.));
            let starts = std::array::from_fn(|code| match code {
                0 => 0.,
                _ => crate::content::srgb::to_linear((code as f32 - 0.5) / 255.),
            });
            let mut coarse = [0; Self::BUCKETS + 1];
            let mut code = 0;
            for (bucket, entry) in coarse.iter_mut().enumerate() {
                let value = bucket as f32 / Self::BUCKETS as f32;
                while code < 255 && starts[code + 1] <= value {
                    code += 1;
                }
                *entry = code as u8;
            }
            Self {
                linear,
                starts,
                coarse,
            }
        })
    }

    /// The sRGB code nearest linear `value` in 0..=1.
    fn encode(&self, value: f32) -> u8 {
        let mut code = usize::from(self.coarse[(value * Self::BUCKETS as f32) as usize]);
        while code < 255 && self.starts[code + 1] <= value {
            code += 1;
        }
        code as u8
    }
}

/// An image's mip chain filtered on the CPU: each level the area-weighted
/// mean of the level above (`footprint`), RGB in linear light where `srgb`.
fn rgba8_levels(image: &image::RgbaImage, srgb: bool) -> Vec<image::RgbaImage> {
    let transfer = Transfer::get();
    let mut levels = vec![image.clone()];
    loop {
        let above = levels.last().unwrap();
        let (width, height) = above.dimensions();
        if width.max(height) == 1 {
            return levels;
        }
        let columns: Vec<_> = (0..(width / 2).max(1))
            .map(|x| footprint(x, width))
            .collect();
        // The weights' numerators are over the level's size along each axis.
        let whole = u64::from(width) * u64::from(height);
        let texels = above.as_raw();
        let mut level = image::RgbaImage::new((width / 2).max(1), (height / 2).max(1));
        for (y, row) in level.rows_mut().enumerate() {
            let (lines, line_count) = footprint(y as u32, height);
            for (texel, (taps, tap_count)) in row.zip(&columns) {
                // Stored values by integer weights, exact; colour's linear
                // values by the same weights in floating point.
                let mut stored = [0u64; 4];
                let mut linear = [0f64; 3];
                for &(line, line_weight) in &lines[..line_count] {
                    let line = line as usize * width as usize;
                    for &(column, column_weight) in &taps[..*tap_count] {
                        let weight = u64::from(line_weight) * u64::from(column_weight);
                        let at = (line + column as usize) * 4;
                        let from = &texels[at..at + 4];
                        if srgb {
                            let share = weight as f64;
                            for channel in 0..3 {
                                linear[channel] +=
                                    share * f64::from(transfer.linear[usize::from(from[channel])]);
                            }
                            stored[3] += weight * u64::from(from[3]);
                        } else {
                            for channel in 0..4 {
                                stored[channel] += weight * u64::from(from[channel]);
                            }
                        }
                    }
                }
                // The nearest code, a half rounding up.
                let nearest = |sum: u64| ((2 * sum + whole) / (2 * whole)) as u8;
                texel.0 = if srgb {
                    let encode = |sum: f64| transfer.encode((sum / whole as f64) as f32);
                    [
                        encode(linear[0]),
                        encode(linear[1]),
                        encode(linear[2]),
                        nearest(stored[3]),
                    ]
                } else {
                    stored.map(nearest)
                };
            }
        }
        levels.push(level);
    }
}

/// A brute-force model of the level below `above`, for the tests of the
/// two filters (`rgba8_levels` and `stages::mip_chains`): each texel's
/// channels as fractional 8-bit codes. Every texel of `above` is repeated
/// once for each texel of the level below along each axis, which makes an
/// image in which a texel of the level below covers a whole block, and the
/// block is averaged: RGB in linear light where `srgb`, by sRGB's transfer
/// function (IEC 61966-2-1) written out here, else as stored.
#[cfg(test)]
pub(crate) fn area_means(above: &image::RgbaImage, srgb: bool) -> Vec<[f64; 4]> {
    let (width, height) = above.dimensions();
    let (below_width, below_height) = ((width / 2).max(1), (height / 2).max(1));
    let decode = |code: u8, colour: bool| {
        let c = f64::from(code) / 255.;
        match colour {
            true if c <= 0.04045 => c / 12.92,
            true => ((c + 0.055) / 1.055).powf(2.4),
            false => c,
        }
    };
    let encode = |value: f64, colour: bool| {
        255. * match colour {
            true if value <= 0.0031308 => value * 12.92,
            true => 1.055 * value.powf(1. / 2.4) - 0.055,
            false => value,
        }
    };
    let mut means = Vec::new();
    for y in 0..below_height {
        for x in 0..below_width {
            let mut sum = [0f64; 4];
            for v in y * height..(y + 1) * height {
                for u in x * width..(x + 1) * width {
                    let texel = above.get_pixel(u / below_width, v / below_height);
                    for channel in 0..4 {
                        sum[channel] += decode(texel[channel], srgb && channel < 3);
                    }
                }
            }
            means.push(std::array::from_fn(|channel| {
                encode(
                    sum[channel] / f64::from(width * height),
                    srgb && channel < 3,
                )
            }));
        }
    }
    means
}

/// An image of `width` by `height` texels whose every channel is drawn
/// from a fixed seed, for the tests of the two filters.
#[cfg(test)]
pub(crate) fn noise(width: u32, height: u32, seed: u64) -> image::RgbaImage {
    let mut state = seed;
    image::RgbaImage::from_fn(width, height, |_, _| {
        image::Rgba(std::array::from_fn(|_| {
            state = state
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            (state >> 56) as u8
        }))
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use wasm_bindgen_test::wasm_bindgen_test;

    #[wasm_bindgen_test(unsupported = test)]
    fn mip_expansion_is_preflighted_without_allocating_images() {
        // A 2x2 image retains two chains of 4 + 1 texels: 40 bytes.
        assert_eq!(
            check_mip_allocation((2, 2), 39),
            Err(ImageError::BudgetExceeded)
        );
        assert_eq!(check_mip_allocation((2, 2), 40), Ok(()));
        assert_eq!(
            check_mip_allocation((16384, 16384), 1 << 30),
            Err(ImageError::BudgetExceeded)
        );
        assert_eq!(check_mip_allocation((16384, 16384), 4 << 30), Ok(()));
        assert_eq!(
            check_mip_allocation((16385, 1), u64::MAX),
            Err(ImageError::InvalidDimensions)
        );
    }

    #[wasm_bindgen_test(unsupported = test)]
    fn prepared_rgba_mips_filter_colour_and_data_separately() {
        fn send<T: Send>() {}
        send::<Rgba8MipChain>();
        send::<ImageError>();
        assert!(Rgba8MipChain::new(image::RgbaImage::new(0, 4)).is_err());
        assert!(Rgba8MipChain::new(image::RgbaImage::new(16385, 1)).is_err());
        let source =
            image::RgbaImage::from_fn(2, 1, |x, _| image::Rgba([if x == 0 { 0 } else { 255 }; 4]));
        let prepared = Rgba8MipChain::new(source.clone()).unwrap();
        assert_eq!(prepared.levels(true)[0], source);
        assert_eq!(prepared.levels(false)[0], source);
        assert_eq!(prepared.levels(false)[1].get_pixel(0, 0).0, [128; 4]);
        assert_eq!(
            prepared.levels(true)[1].get_pixel(0, 0).0,
            [188, 188, 188, 128]
        );
        let odd = Rgba8MipChain::new(image::RgbaImage::new(7, 5)).unwrap();
        assert_eq!(
            odd.levels(false)
                .iter()
                .map(|m| m.dimensions())
                .collect::<Vec<_>>(),
            [(7, 5), (3, 2), (1, 1)]
        );
        // Each texel of the level below covers exactly two texels: a wider
        // kernel (the Triangle resize this replaced) would bleed the halves
        // into each other.
        let halves = image::RgbaImage::from_fn(4, 1, |x, _| image::Rgba([(x / 2 * 255) as u8; 4]));
        let halves = Rgba8MipChain::new(halves).unwrap();
        for srgb in [false, true] {
            assert_eq!(
                halves.levels(srgb)[1].as_raw(),
                &[0, 0, 0, 0, 255, 255, 255, 255]
            );
        }
    }

    // Plausible defect: a level leaves out part of the level above (the odd
    // row or column of a size that is not a power of two), weighs its
    // footprint's texels wrongly, averages colour as stored or data in
    // linear light, or filters alpha as colour. The oracle is the
    // brute-force area model (`area_means`) of each level from the level
    // above it: data and alpha are its nearest code, colour within the
    // float error of a table against the formula.
    #[wasm_bindgen_test(unsupported = test)]
    fn prepared_levels_are_the_area_mean_of_the_level_above() {
        for (seed, (width, height)) in [(7, 5), (8, 4), (1, 6), (5, 1), (9, 9)]
            .into_iter()
            .enumerate()
        {
            let chain = Rgba8MipChain::new(noise(width, height, seed as u64 + 1)).unwrap();
            for srgb in [false, true] {
                let levels = chain.levels(srgb);
                assert_eq!(levels.len() as u32, 32 - width.max(height).leading_zeros());
                for (above, level) in levels.iter().zip(&levels[1..]) {
                    assert_eq!(
                        level.dimensions(),
                        ((above.width() / 2).max(1), (above.height() / 2).max(1))
                    );
                    for (texel, mean) in level.pixels().zip(area_means(above, srgb)) {
                        for channel in 0..4 {
                            let off = (f64::from(texel[channel]) - mean[channel]).abs();
                            assert!(
                                off <= 0.5 + 1e-3,
                                "{width}x{height} srgb {srgb} channel {channel}: {} for a mean of {}",
                                texel[channel],
                                mean[channel]
                            );
                        }
                    }
                }
            }
        }
    }
}
